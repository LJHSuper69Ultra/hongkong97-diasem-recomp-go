// Command hangul adds the glyphs the Korean text needs to the game font.
//
// The original font ($83:8000, assets/font/font.png) has no Hangul. Extra
// 16x16 glyphs live in a second sheet placed right after it
// (assets/font/hangul.png at $84:8600, glyph codes from $0218 up), with
// assets/font/hangul.txt naming the character of each glyph. This tool
// scans every 16x16 text file listed in the manifest, draws each character
// that has no glyph yet with the Neo둥근모 pixel font (neodgm.ttf, SIL OFL
// 1.1, see neodgm-OFL.txt) and appends it to the sheet and the list.
//
//	go run ./tools/hangul            # add missing glyphs
//	go run ./tools/hangul -rebuild   # redraw the sheet with only the glyphs in use
package main

import (
	_ "embed"
	"flag"
	"fmt"
	"image"
	"image/color"
	"os"
	"path/filepath"

	"golang.org/x/image/font"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/math/fixed"

	af "hk97/assetfmt"
)

//go:embed neodgm.ttf
var neodgm []byte

const (
	maxCode = 0x3FF // the text renderer reaches $83:8000 + code*64 within two banks
	scale   = 8     // rasterize at 8x and sample pixel centres (crisp 1-bit glyphs)
)

const header = `# 16x16 glyphs appended to the game font (sheet: hangul.png, placed right
# after font.png). "@XXXX" is the code of the first glyph; the characters
# follow in code order, 8 per sheet row. Generated by tools/hangul from the
# Neo둥근모 font (SIL OFL 1.1, tools/hangul/neodgm-OFL.txt).
`

func main() {
	dir := flag.String("assets", "assets", "assets directory")
	rebuild := flag.Bool("rebuild", false, "drop glyphs no text uses and redraw the sheet")
	flag.Parse()
	if err := run(*dir, *rebuild); err != nil {
		fmt.Fprintln(os.Stderr, "hangul:", err)
		os.Exit(1)
	}
}

func run(dir string, rebuild bool) error {
	m, err := af.LoadManifest(dir)
	if err != nil {
		return err
	}
	var sheet *af.Item
	for _, it := range m.Items {
		if it.Kind == "font" && it.Chars != "" {
			sheet = it
		}
	}
	if sheet == nil {
		return fmt.Errorf("manifest has no font item with a glyph list (\"chars\")")
	}
	listPath := filepath.Join(dir, sheet.Chars)
	pngPath := filepath.Join(dir, sheet.File)
	src, err := os.ReadFile(listPath)
	if err != nil {
		return err
	}
	first, chars, err := af.ReadGlyphList(string(src))
	if err != nil {
		return err
	}

	// characters used by 16x16 text that the original font lacks
	var used []rune
	seen := map[rune]bool{}
	for _, it := range m.Items {
		if it.Kind != "text" || it.Renderer != "16" {
			continue
		}
		b, err := os.ReadFile(filepath.Join(dir, it.File))
		if err != nil {
			return err
		}
		for _, r := range af.TextChars(string(b)) {
			r = af.WideAlias(r)
			if !seen[r] {
				seen[r] = true
				used = append(used, r)
			}
		}
	}
	// (the original glyphs are in the table before registration)
	inExtra := map[rune]bool{}
	for _, r := range chars {
		inExtra[r] = true
	}
	var need []rune
	for _, r := range used {
		if _, ok := af.Glyph16(r); !ok || inExtra[r] {
			need = append(need, r)
		}
	}

	var list []rune
	if rebuild {
		list = need
	} else {
		list = append(list, chars...)
		for _, r := range need {
			if !inExtra[r] {
				list = append(list, r)
			}
		}
	}
	if int(first)+len(list)-1 > maxCode {
		return fmt.Errorf("%d glyphs do not fit (codes %04X-%04X, limit %04X)", len(list), first, int(first)+len(list)-1, maxCode)
	}
	if n := (len(list) + 7) / 8 * 16 * 128 / 4; n > sheet.Slot {
		return fmt.Errorf("sheet needs %d bytes, slot is %d", n, sheet.Slot)
	}

	// draw (existing glyphs are kept as they are unless rebuilding, so hand
	// edits to the sheet survive)
	var old []uint8
	oldRows := 0
	if !rebuild {
		if pix, w, h, err := af.ReadPNG(pngPath); err == nil && w == 128 {
			old, oldRows = pix, h
		}
	}
	face, err := newFace()
	if err != nil {
		return err
	}
	h := (len(list) + 7) / 8 * 16
	pix := make([]uint8, 128*h)
	added := 0
	for i, r := range list {
		x0, y0 := i%8*16, i/8*16
		if !rebuild && i < len(chars) && y0+16 <= oldRows {
			for y := 0; y < 16; y++ {
				copy(pix[(y0+y)*128+x0:(y0+y)*128+x0+16], old[(y0+y)*128+x0:(y0+y)*128+x0+16])
			}
			continue
		}
		g, err := drawGlyph(face, r)
		if err != nil {
			return err
		}
		for y := 0; y < 16; y++ {
			for x := 0; x < 16; x++ {
				pix[(y0+y)*128+x0+x] = g[y*16+x]
			}
		}
		added++
	}
	gray := []color.Color{color.RGBA{255, 255, 255, 255}, color.RGBA{170, 170, 170, 255}, color.RGBA{85, 85, 85, 255}, color.RGBA{0, 0, 0, 255}}
	if err := af.WritePNG(pngPath, pix, 128, max(h, 16), gray); err != nil {
		return err
	}
	if err := os.WriteFile(listPath, []byte(af.FormatGlyphList(header, first, list)), 0o644); err != nil {
		return err
	}
	fmt.Printf("hangul: %d glyphs (codes %04X-%04X), %d drawn\n", len(list), first, int(first)+len(list)-1, added)
	return nil
}

func newFace() (font.Face, error) {
	f, err := opentype.Parse(neodgm)
	if err != nil {
		return nil, err
	}
	return opentype.NewFace(f, &opentype.FaceOptions{Size: 16 * scale, DPI: 72, Hinting: font.HintingNone})
}

// drawGlyph renders r into a 16x16 cell (pixel value 1 = ink). Full-width
// ASCII forms (U+FF01-FF5E) are drawn with the half-width glyph at the left.
func drawGlyph(face font.Face, r rune) ([]uint8, error) {
	draw1 := r
	if r >= 0xFF01 && r <= 0xFF5E {
		draw1 = r - 0xFF01 + '!'
	}
	if _, ok := face.GlyphAdvance(draw1); !ok {
		return nil, fmt.Errorf("the font has no glyph for %q", r)
	}
	img := image.NewAlpha(image.Rect(0, 0, 16*scale, 16*scale))
	d := &font.Drawer{Dst: img, Src: image.Opaque, Face: face, Dot: fixed.P(0, 12*scale)}
	d.DrawString(string(draw1))
	g := make([]uint8, 256)
	for y := 0; y < 16; y++ {
		for x := 0; x < 16; x++ {
			if img.AlphaAt(x*scale+scale/2, y*scale+scale/2).A >= 128 {
				g[y*16+x] = 1
			}
		}
	}
	return g, nil
}
